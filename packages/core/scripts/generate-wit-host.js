import fs from "fs";
import os from "os";
import path from "path";
import { execFileSync } from "child_process";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "../../..");
const witPath = path.resolve(repoRoot, "packages/types/wit/omni.wit");
const outDir = path.resolve(__dirname, "../src/sandbox/wit-host");
const jcoBin = path.resolve(repoRoot, "node_modules/.bin/jco");

const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "omni-jco-host-"));

try {
  // Canonical ABI core module signature matching omni.wit
  const stubWat = `(module
  (import "omni:plugin/ui@0.1.0" "render" (func (param i32 i32)))
  (import "omni:plugin/ui@0.1.0" "render-component" (func (param i32 i32 i32 i32)))
  (import "omni:plugin/nostr@0.1.0" "subscribe" (func (param i32 i32 i32)))
  (import "omni:plugin/nostr@0.1.0" "publish" (func (param i32 i32 i32)))
  (import "omni:plugin/nostr@0.1.0" "fetch" (func (param i32 i32 i32)))
  (import "omni:plugin/nostr@0.1.0" "get-public-key" (func (param i32)))
  (memory (export "memory") 1)
  (func (export "cabi_realloc") (param i32 i32 i32 i32) (result i32) i32.const 0)
  (func (export "init") (result i32) i32.const 0)
  (func (export "cabi_post_init") (param i32))
  (func (export "handle-action") (param i32 i32 i32 i32) (result i32) i32.const 0)
  (func (export "cabi_post_handle-action") (param i32))
)
`;

  const watFile = path.join(tmpDir, "omni.wat");
  const coreWasm = path.join(tmpDir, "omni.core.wasm");
  const embeddedWasm = path.join(tmpDir, "omni.embedded.wasm");
  const componentWasm = path.join(tmpDir, "omni-component.wasm");
  const transpileDir = path.join(tmpDir, "transpiled");

  fs.writeFileSync(watFile, stubWat, "utf8");

  execFileSync(jcoBin, ["parse", watFile, "-o", coreWasm], { stdio: "pipe" });
  execFileSync(
    jcoBin,
    ["embed", coreWasm, "--wit", witPath, "--string-encoding", "utf16", "-o", embeddedWasm],
    { stdio: "pipe" }
  );
  execFileSync(jcoBin, ["new", embeddedWasm, "-o", componentWasm], { stdio: "pipe" });
  execFileSync(
    jcoBin,
    [
      "transpile",
      componentWasm,
      "-o",
      transpileDir,
      "--instantiation",
      "async",
      "--no-nodejs-compat",
      "-q"
    ],
    { stdio: "pipe" }
  );

  fs.mkdirSync(outDir, { recursive: true });

  // Write generated JS as TypeScript module with @ts-nocheck header for seamless tsc compilation.
  // Replace dynamic `new URL(\`./\${name}\`, import.meta.url)` fallback so Vite's static asset import glob
  // does not rewrite it into `import.meta.glob("./*")` (which tries to load .d.ts.map JSON files as ES modules).
  let generatedJs = fs.readFileSync(path.join(transpileDir, "omni-component.js"), "utf8");
  generatedJs = generatedJs.replace(
    /if\s*\(!getCoreModule\)\s*getCoreModule\s*=\s*\(name\)\s*=>\s*fetchCompile\(new URL\(`\.\/\$\{name\}`,\s*import\.meta\.url\)\);/g,
    'if (!getCoreModule) throw new Error("getCoreModule is required");'
  );
  fs.writeFileSync(
    path.join(outDir, "omni-component.ts"),
    `// @ts-nocheck\n// Auto-generated by jco from packages/types/wit/omni.wit. DO NOT EDIT.\n${generatedJs}`,
    "utf8"
  );

  // Export core2 and core3 lowering trampoline shims as inlined Uint8Arrays
  const core2Bytes = Array.from(
    fs.readFileSync(path.join(transpileDir, "omni-component.core2.wasm"))
  );
  const core3Bytes = Array.from(
    fs.readFileSync(path.join(transpileDir, "omni-component.core3.wasm"))
  );

  const shimsTs = `// Auto-generated by jco from packages/types/wit/omni.wit. DO NOT EDIT.
export const CORE2_WASM_BYTES = new Uint8Array([${core2Bytes.join(",")}]);
export const CORE3_WASM_BYTES = new Uint8Array([${core3Bytes.join(",")}]);
`;
  fs.writeFileSync(path.join(outDir, "core-shims.ts"), shimsTs, "utf8");

  console.log("✅ Generated jco WIT host bindings in packages/core/src/sandbox/wit-host");
} finally {
  fs.rmSync(tmpDir, { recursive: true, force: true });
}
